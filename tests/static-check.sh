#!/usr/bin/env bash
# Maintained source only; no service starts, admission or external requests.
set -euo pipefail
cd "$(dirname "$0")/.."
while IFS= read -r -d '' file; do node --check "$file"; done < <(find tests scripts upstream -type f \( -name '*.js' -o -name '*.cjs' \) -print0)
while IFS= read -r -d '' file; do bash -n "$file"; done < <(find tests scripts -type f -name '*.sh' -print0)
python3 - <<'PY'
from pathlib import Path
for folder in ('tests', 'scripts'):
    for file in Path(folder).rglob('*.py'):
        compile(file.read_bytes(), str(file), 'exec')
print('PASS: Python syntax without generated bytecode')
PY
if command -v shellcheck >/dev/null; then
  shellcheck tests/offline-check.sh tests/static-check.sh
else
  echo 'SKIP: ShellCheck (not installed; required separately in CI)'
fi
if command -v actionlint >/dev/null; then
  actionlint
else
  echo 'SKIP: actionlint (not installed; required separately in CI)'
fi
echo 'PASS: available static checks; PHP lint is also run in CI'
